    verify_short_binding()

    # Rebind only this process to isolated short-track inputs/outputs.
    base.MANUSCRIPT = SHORT_MD
    base.OUT_TEX = OUT_TEX
    base.OUT_PDF = OUT_PDF
    base.OUT_LOG = OUT_LOG
    base.OUT_AUDIT = OUT_AUDIT
    base.EXPECTED_MANUSCRIPT = EXPECTED_SHORT_MD
    base.TABLE_CAPTIONS = TABLE_CAPTIONS
    base.TABLE_SPECS = TABLE_SPECS
    base.TABLE_HEADER_KEYS = TABLE_HEADER_KEYS
    base.verify_bindings = verify_short_binding
    base.make_tex = make_short_tex

    result = base.build_and_audit()
    write_short_audit(result)

