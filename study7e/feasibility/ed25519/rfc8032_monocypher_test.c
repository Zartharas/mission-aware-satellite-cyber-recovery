#include <stdint.h>
#include <stdio.h>
#include <string.h>

#include "monocypher-ed25519.h"

static const uint8_t public_key[32] = {
    0xd7,0x5a,0x98,0x01,0x82,0xb1,0x0a,0xb7,
    0xd5,0x4b,0xfe,0xd3,0xc9,0x64,0x07,0x3a,
    0x0e,0xe1,0x72,0xf3,0xda,0xa6,0x23,0x25,
    0xaf,0x02,0x1a,0x68,0xf7,0x07,0x51,0x1a
};

static const uint8_t signature[64] = {
    0xe5,0x56,0x43,0x00,0xc3,0x60,0xac,0x72,
    0x90,0x86,0xe2,0xcc,0x80,0x6e,0x82,0x8a,
    0x84,0x87,0x7f,0x1e,0xb8,0xe5,0xd9,0x74,
    0xd8,0x73,0xe0,0x65,0x22,0x49,0x01,0x55,
    0x5f,0xb8,0x82,0x15,0x90,0xa3,0x3b,0xac,
    0xc6,0x1e,0x39,0x70,0x1c,0xf9,0xb4,0x6b,
    0xd2,0x5b,0xf5,0xf0,0x59,0x5b,0xbe,0x24,
    0x65,0x51,0x41,0x43,0x8e,0x7a,0x10,0x0b
};

int main(void)
{
    uint8_t mutated_signature[64];
    uint8_t zero_signature[64] = {0};
    const uint8_t empty_message[1] = {0};
    const uint8_t changed_message[1] = {0};

    if (crypto_ed25519_check(signature, public_key, empty_message, 0) != 0)
    {
        return 1;
    }

    memcpy(mutated_signature, signature, sizeof(mutated_signature));
    mutated_signature[0] ^= 0x01u;
    if (crypto_ed25519_check(mutated_signature, public_key, empty_message, 0) == 0)
    {
        return 2;
    }

    if (crypto_ed25519_check(zero_signature, public_key, empty_message, 0) == 0)
    {
        return 3;
    }

    if (crypto_ed25519_check(signature, public_key, changed_message, sizeof(changed_message)) == 0)
    {
        return 4;
    }

    puts("MONOCYPHER_RFC8032_ED25519_VERIFY=PASS");
    puts("MONOCYPHER_MUTATED_SIGNATURE_REJECT=PASS");
    puts("MONOCYPHER_ZERO_SIGNATURE_REJECT=PASS");
    puts("MONOCYPHER_CHANGED_MESSAGE_REJECT=PASS");
    return 0;
}
